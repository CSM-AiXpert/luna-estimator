create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  estimate_number text not null,
  status text not null default 'draft',
  customer_name text not null,
  customer_phone text,
  customer_email text,
  property_address text not null,
  property_type text,
  project_type text,
  notes text,
  internal_notes text,
  lead_source text,
  tags jsonb,
  crm_contact_id text,
  crm_opportunity_id text,
  crm_estimate_id text,
  crm_sync_status text default 'not_needed',
  subtotal numeric(10, 2) default 0,
  tax_rate numeric(5, 2) default 0,
  tax_amount numeric(10, 2) default 0,
  discount_amount numeric(10, 2) default 0,
  total numeric(10, 2) default 0,
  deposit_percent integer default 50,
  deposit_amount numeric(10, 2) default 0,
  customer_signed_at timestamptz,
  customer_signature_name text,
  estimator_signed_at timestamptz,
  estimator_signature_name text,
  unsigned_pdf_url text,
  signed_pdf_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.rooms (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects (id) on delete cascade,
  name text not null,
  sort_order integer default 0,
  length numeric(8, 2),
  width numeric(8, 2),
  height numeric(8, 2),
  wall_sq_ft numeric(10, 2),
  ceiling_sq_ft numeric(10, 2),
  total_sq_ft numeric(10, 2),
  door_count integer default 0,
  window_count integer default 0,
  trim_linear_ft numeric(10, 2),
  baseboard_linear_ft numeric(10, 2),
  has_drywall_repair jsonb,
  paint_scope jsonb,
  texture_scope jsonb,
  prep_complexity text default 'standard',
  repair_complexity text default 'none',
  paint_brand text,
  paint_color text,
  paint_color_code text,
  finish_type text,
  product_line text,
  coats integer default 2,
  photos jsonb,
  ai_visualization_url text,
  notes text,
  internal_notes text,
  subtotal numeric(10, 2) default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.line_items (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects (id) on delete cascade,
  room_id bigint references public.rooms (id) on delete set null,
  description text not null,
  category text,
  scope text,
  quantity numeric(10, 2) default 1,
  unit text default 'ea',
  rate numeric(10, 2) default 0,
  subtotal numeric(10, 2) default 0,
  sort_order integer default 0,
  is_internal integer default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.media (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects (id) on delete cascade,
  room_id bigint references public.rooms (id) on delete set null,
  url text not null,
  caption text,
  category text default 'general',
  include_on_pdf integer default 1,
  is_internal integer default 0,
  sort_order integer default 0,
  created_at timestamptz not null default now()
);

create index if not exists projects_user_id_idx on public.projects (user_id);
create index if not exists rooms_project_id_idx on public.rooms (project_id);
create index if not exists line_items_project_id_idx on public.line_items (project_id);
create index if not exists media_project_id_idx on public.media (project_id);
